"use strict";

const fs = require("fs");
const path = require("path");
const {
  HOOK_MARKER, LEGACY_HOOK_MARKERS, ReviewError, assertClean, git, gitCommonDir,
  listWorktrees, managedReviewPath, normalizeRole, normalizeTaskId, readRef,
  refsFor, resolveRepository, statusLines, tryGit,
} = require("./local-review-common");

function prepareReviewWorktree(options) {
  const repo = resolveRepository(options.repo || process.cwd());
  const task = normalizeTaskId(options.task);
  const role = normalizeRole(options.role);
  const refs = refsFor(task);
  const candidateSha = readRef(repo, refs.candidate);
  if (!candidateSha) {
    throw new ReviewError(`No local review candidate exists for #${task}.`, "NO_CANDIDATE");
  }

  if (options.inPlace) {
    assertClean(repo);
    git(repo, ["checkout", "--detach", "--quiet", candidateSha]);
    git(repo, ["reset", "--hard", "--quiet", candidateSha]);
    return { repo, task, role, candidateSha, path: repo, inPlace: true };
  }

  const destination = managedReviewPath(repo, task, role);
  const registered = listWorktrees(repo).find((entry) => entry.worktree && path.resolve(entry.worktree) === destination);

  if (registered) {
    const dirty = statusLines(destination);
    if (dirty.length) {
      throw new ReviewError(
        `Managed ${role} review worktree has local changes at ${destination}. Remove them before refreshing the candidate:\n${dirty.slice(0, 8).join("\n")}`,
        "REVIEW_WORKTREE_DIRTY"
      );
    }
    git(destination, ["checkout", "--detach", "--quiet", candidateSha]);
    git(destination, ["reset", "--hard", "--quiet", candidateSha]);
  } else {
    if (fs.existsSync(destination)) {
      throw new ReviewError(
        `Refusing to overwrite unregistered path ${destination}. Remove or rename it, then retry.`,
        "REVIEW_PATH_OCCUPIED"
      );
    }
    fs.mkdirSync(path.dirname(destination), { recursive: true, mode: 0o700 });
    git(repo, ["worktree", "add", "--detach", "--quiet", destination, candidateSha]);
  }

  return { repo, task, role, candidateSha, path: destination };
}

function hookPath(repo) {
  const configured = tryGit(repo, ["config", "--path", "--get", "core.hooksPath"]);
  if (configured.ok && configured.output) {
    const value = configured.output;
    const resolved = path.isAbsolute(value) ? value : path.resolve(repo, value);
    return { path: path.join(resolved, "pre-push"), customHooksPath: true };
  }
  return { path: path.join(gitCommonDir(repo), "hooks", "pre-push"), customHooksPath: false };
}

function guardHookBody() {
  return [
    "#!/bin/sh",
    `# ${HOOK_MARKER}`,
    "# Generated by QuadWork. This guard is deliberately branch-scoped: it blocks",
    "# only branches with an active local-review candidate and leaves unrelated",
    "# branches untouched. The validated publish command sets the one-shot",
    "# QUADWORK_REVIEW_PUBLISH=1 bypass after both exact-SHA approvals exist.",
    "",
    'if [ "${QUADWORK_REVIEW_PUBLISH:-}" = "1" ]; then',
    "  exit 0",
    "fi",
    "",
    'COMMON="$(git rev-parse --path-format=absolute --git-common-dir 2>/dev/null || git rev-parse --git-common-dir 2>/dev/null || true)"',
    'if [ -z "$COMMON" ]; then',
    "  exit 0",
    "fi",
    'case "$COMMON" in',
    "  /*) ;;",
    '  *) COMMON="$(pwd)/$COMMON" ;;',
    "esac",
    'REVIEW_DIR="$COMMON/quadwork/reviews"',
    'if [ ! -d "$REVIEW_DIR" ]; then',
    "  exit 0",
    "fi",
    "",
    "# Git supplies one line per ref on stdin:",
    "#   <local-ref> <local-sha> <remote-ref> <remote-sha>",
    "# Node is already a QuadWork prerequisite and lets the hook parse the atomic",
    "# JSON state without depending on jq or platform-specific shell extensions.",
    'UPDATES="$(cat)"',
    "QUADWORK_PUSH_UPDATES=\"$UPDATES\" node - \"$REVIEW_DIR\" <<'QUADWORK_REVIEW_HOOK'",
    'const fs = require("fs");',
    'const path = require("path");',
    "",
    "const reviewDir = process.argv[2];",
    'const updates = String(process.env.QUADWORK_PUSH_UPDATES || "")',
    "  .split(/\\r?\\n/)",
    "  .filter(Boolean)",
    "  .map((line) => {",
    '    const [localRef = "", localSha = "", remoteRef = "", remoteSha = ""] = line.trim().split(/\\s+/);',
    '    const branchRef = localRef.startsWith("refs/heads/") ? localRef : remoteRef;',
    '    const branch = branchRef.startsWith("refs/heads/") ? branchRef.slice("refs/heads/".length) : null;',
    "    return { branch, localSha, remoteSha };",
    "  })",
    "  .filter((entry) => entry.branch);",
    "",
    "if (updates.length === 0) process.exit(0);",
    "",
    "let states = [];",
    "try {",
    "  states = fs.readdirSync(reviewDir)",
    '    .filter((name) => name.endsWith(".json"))',
    "    .map((name) => {",
    '      try { return JSON.parse(fs.readFileSync(path.join(reviewDir, name), "utf8")); }',
    "      catch { return null; }",
    "    })",
    "    .filter(Boolean);",
    "} catch {",
    "  process.exit(0);",
    "}",
    "",
    "for (const update of updates) {",
    "  const state = states.find((candidate) =>",
    "    candidate &&",
    "    candidate.branch === update.branch &&",
    '    typeof candidate.candidateSha === "string" &&',
    "    candidate.candidateSha.length === 40",
    "  );",
    "  if (!state) continue;",
    "",
    '  const task = state.task || "<ticket>";',
    '  const base = state.base && state.base.ref ? state.base.ref : "origin/main";',
    "  process.stderr.write(\"QuadWork blocked a direct push of reviewed branch '\" + update.branch + \"'.\\n\");",
    "  process.stderr.write(\"Keep review revisions local; a new candidate invalidates old approvals.\\n\");",
    "  process.stderr.write(\"  npx quadwork review candidate \" + task + \" --base \" + base + \"\\n\");",
    "  process.stderr.write(\"  npx quadwork review publish \" + task + \" --title '<title>' --body-file <file>\\n\");",
    "  process.stderr.write(\"Emergency human override: QUADWORK_REVIEW_PUBLISH=1 git push ...\\n\");",
    "  process.exit(1);",
    "}",
    "QUADWORK_REVIEW_HOOK",
    "",
  ].join("\n");
}
function installPrePushGuard(repoInput) {
  const repo = resolveRepository(repoInput || process.cwd());
  const target = hookPath(repo);
  let existing = "";
  try { existing = fs.readFileSync(target.path, "utf8"); } catch (error) {
    if (error.code !== "ENOENT") {
      return { installed: false, reason: `Cannot read ${target.path}: ${error.message}`, path: target.path };
    }
  }

  if (existing.includes(HOOK_MARKER)) {
    return { installed: true, alreadyInstalled: true, path: target.path, customHooksPath: target.customHooksPath };
  }
  const generatedByOlderVersion = LEGACY_HOOK_MARKERS.some((marker) => existing.includes(marker));
  if (existing.trim() && !generatedByOlderVersion) {
    return {
      installed: false,
      reason: `Existing pre-push hook left untouched at ${target.path}`,
      path: target.path,
      customHooksPath: target.customHooksPath,
    };
  }

  try {
    fs.mkdirSync(path.dirname(target.path), { recursive: true, mode: 0o700 });
    fs.writeFileSync(target.path, guardHookBody(), { mode: 0o755 });
    try { fs.chmodSync(target.path, 0o755); } catch {}
    return { installed: true, alreadyInstalled: false, upgraded: generatedByOlderVersion, path: target.path, customHooksPath: target.customHooksPath };
  } catch (error) {
    return { installed: false, reason: `Cannot install ${target.path}: ${error.message}`, path: target.path };
  }
}

module.exports = { guardHookBody, hookPath, installPrePushGuard, prepareReviewWorktree };
